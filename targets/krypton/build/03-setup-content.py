#!/usr/bin/env python3
"""Krypton onboarding content only. Levels 0, 1, 3, 4, 5's actual puzzle
content (Base64, ROT13, substitution, two Vigenere variants) is
generated at CONTAINER START by entrypoint.sh from per-team secrets, not
baked in here at build time -- see docs/security-audit-status.md. Levels
2 and 6 (which need the compiled `encrypt` binaries) are handled
separately too, also at container start now for level 2 (level 6 still
build-time for now)."""
import os
import subprocess


def write(path, content, owner, mode=0o440):
    with open(path, "w", newline="\n") as f:
        f.write(content)
    os.chmod(path, mode)
    subprocess.run(["chown", owner, path], check=True)


# ---- "Krypton: Start Here" onboarding challenge (build_krypton.py) -----
# Lives in krypton0's home, NOT krypton1's -- krypton1's login password
# used to be a static, build-time value (level 0's flag was a fixed
# string embedded in the CTFd description), which made it safe to also
# hardcode into this onboarding step. Now that krypton0 is a real
# account of its own with the fixed, publicly-known password ("krypton0",
# see 02-set-passwords.sh) and krypton1's password is per-team dynamic
# (generated by entrypoint.sh from level 0's flag), the onboarding step
# has to use the ONE account whose password is still knowable at
# build time -- krypton0. welcome.txt here is a separate, static file
# from krypton0's real puzzle content (encoded.txt, written per-team by
# entrypoint.sh into this same home directory).
write("/home/krypton0/welcome.txt", "WELCOME_TO_KRYPTON\n", "krypton0:krypton0", 0o444)

print("Onboarding content written; levels 0/1/3/4/5 content deferred to entrypoint.sh.")
